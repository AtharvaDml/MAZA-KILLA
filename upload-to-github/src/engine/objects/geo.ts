import {
  BufferAttribute, BufferGeometry, Color, Euler, Matrix4, Quaternion, Vector2, Vector3, LatheGeometry, Shape,
  ExtrudeGeometry, BoxGeometry,
} from 'three';
import { mergeGeometries, mergeVertices } from 'three/examples/jsm/utils/BufferGeometryUtils.js';
import { valueNoise3 } from '../util/noise';
import { smoothstep } from '../util/math';

export type V3 = [number, number, number];

export interface PieceOpts {
  color: number;
  tint?: number;
  jitter?: number;
  jitterFreq?: number;
  colorNoise?: number;
  colorFreq?: number;
  smooth?: boolean;
  /** Darken toward the bottom: [y0, y1, minFactor]. */
  ao?: [number, number, number?];
  pos?: V3;
  rot?: V3;
  quat?: Quaternion;
  scale?: V3 | number;
  seed?: number;
  /** Blend toward `color` with height. */
  top?: { color: number; from: number; to: number };
  deform?: (p: Vector3) => void;
  colorFn?: (p: Vector3, c: Color) => void;
  uvFn?: (p: Vector3, uv: Vector2) => [number, number];
}

const tmpV = new Vector3();
const tmpUv = new Vector2();
const tmpC = new Color();
const tmpTop = new Color();

/**
 * Builds a single merged, indexed geometry from primitive pieces with handmade imperfection:
 * position-coherent jitter (no cracks between pieces), vertex colour noise, ground darkening,
 * and a per-vertex `aTint` mask so instance colours only recolour the right parts.
 */
export class PartBuilder {
  private pieces: BufferGeometry[] = [];
  constructor(private readonly withUv = false) {}

  add(geo: BufferGeometry, o: PieceOpts): this {
    let g = geo;
    if (!this.withUv && g.getAttribute('uv')) g.deleteAttribute('uv');
    if (o.smooth) {
      // Merge by position so normals smooth across seams; uv is regenerated by uvFn when given.
      g.deleteAttribute('normal');
      if (o.uvFn && g.getAttribute('uv')) g.deleteAttribute('uv');
      g = mergeVertices(g, 1e-4);
    }
    const s = o.scale === undefined ? [1, 1, 1] : typeof o.scale === 'number' ? [o.scale, o.scale, o.scale] : o.scale;
    const q = o.quat ?? new Quaternion().setFromEuler(new Euler(...(o.rot ?? [0, 0, 0])));
    g.applyMatrix4(new Matrix4().compose(new Vector3(...(o.pos ?? [0, 0, 0])), q, new Vector3(s[0], s[1], s[2])));

    const pos = g.getAttribute('position') as BufferAttribute;
    const n = pos.count;
    const seed = o.seed ?? 1;
    if (o.deform || o.jitter) {
      const f = o.jitterFreq ?? 2;
      const a = o.jitter ?? 0;
      for (let i = 0; i < n; i++) {
        tmpV.fromBufferAttribute(pos, i);
        if (o.deform) o.deform(tmpV);
        if (a) {
          const x = tmpV.x * f, y = tmpV.y * f, z = tmpV.z * f;
          tmpV.x += (valueNoise3(x, y, z, seed) - 0.5) * 2 * a;
          tmpV.y += (valueNoise3(x + 31.7, y, z, seed) - 0.5) * 2 * a;
          tmpV.z += (valueNoise3(x, y + 17.3, z, seed) - 0.5) * 2 * a;
        }
        pos.setXYZ(i, tmpV.x, tmpV.y, tmpV.z);
      }
    }
    if (o.smooth || o.jitter || o.deform || !g.getAttribute('normal')) g.computeVertexNormals();

    // Colours (linear) with noise, ao and optional gradient.
    const base = new Color(o.color);
    const colors = new Float32Array(n * 3);
    const cn = o.colorNoise ?? 0.08;
    const cf = o.colorFreq ?? 3;
    if (o.top) tmpTop.set(o.top.color);
    for (let i = 0; i < n; i++) {
      tmpV.fromBufferAttribute(pos, i);
      tmpC.copy(base);
      if (o.top) tmpC.lerp(tmpTop, smoothstep(o.top.from, o.top.to, tmpV.y));
      let k = 1 + (valueNoise3(tmpV.x * cf, tmpV.y * cf, tmpV.z * cf, seed + 5) - 0.5) * 2 * cn;
      if (o.ao) k *= (o.ao[2] ?? 0.55) + (1 - (o.ao[2] ?? 0.55)) * smoothstep(o.ao[0], o.ao[1], tmpV.y);
      tmpC.multiplyScalar(k);
      if (o.colorFn) o.colorFn(tmpV, tmpC);
      colors[i * 3] = tmpC.r;
      colors[i * 3 + 1] = tmpC.g;
      colors[i * 3 + 2] = tmpC.b;
    }
    g.setAttribute('color', new BufferAttribute(colors, 3));
    g.setAttribute('aTint', new BufferAttribute(new Float32Array(n).fill(o.tint ?? 0), 1));

    if (this.withUv) {
      let uv = g.getAttribute('uv') as BufferAttribute | undefined;
      if (!uv) {
        uv = new BufferAttribute(new Float32Array(n * 2), 2);
        g.setAttribute('uv', uv);
      }
      if (o.uvFn) {
        for (let i = 0; i < n; i++) {
          tmpV.fromBufferAttribute(pos, i);
          tmpUv.fromBufferAttribute(uv, i);
          const [u, v] = o.uvFn(tmpV, tmpUv);
          uv.setXY(i, u, v);
        }
      }
    }
    for (const name of Object.keys(g.attributes)) {
      if (!['position', 'normal', 'color', 'aTint', ...(this.withUv ? ['uv'] : [])].includes(name)) g.deleteAttribute(name);
    }
    if (!g.index) g = mergeVertices(g, 1e-5);
    this.pieces.push(g);
    return this;
  }

  build(): BufferGeometry {
    const g = mergeGeometries(this.pieces, false);
    if (!g) throw new Error('PartBuilder: merge failed');
    g.computeBoundingSphere();
    g.computeBoundingBox();
    return g;
  }
}

export function lathe(points: [number, number][], segments = 16): LatheGeometry {
  return new LatheGeometry(points.map(([r, y]) => new Vector2(r, y)), segments);
}

/** Quad(s) for additive camera-facing halos. */
export function glowQuads(centers: { c: V3; size: number }[]): BufferGeometry {
  const pos: number[] = [], uv: number[] = [], cen: number[] = [], idx: number[] = [];
  centers.forEach(({ c, size }, q) => {
    const h = size / 2;
    const corners = [[-h, -h], [h, -h], [h, h], [-h, h]];
    corners.forEach(([x, y], i) => {
      pos.push(x, y, 0);
      uv.push(i === 1 || i === 2 ? 1 : 0, i >= 2 ? 1 : 0);
      cen.push(c[0], c[1], c[2]);
    });
    const b = q * 4;
    idx.push(b, b + 1, b + 2, b, b + 2, b + 3);
  });
  const g = new BufferGeometry();
  g.setAttribute('position', new BufferAttribute(new Float32Array(pos), 3));
  g.setAttribute('uv', new BufferAttribute(new Float32Array(uv), 2));
  g.setAttribute('aCenter', new BufferAttribute(new Float32Array(cen), 3));
  g.setIndex(idx);
  g.computeBoundingSphere();
  return g;
}

/** Flag cloth: a swallow-tailed pennant on a grid so it can wave. Lies in XY, attached at x=0. */
export function pennantGeometry(length: number, height: number, notch: number, color: number, seed = 3): BufferGeometry {
  const NU = 22, NV = 10;
  const pos: number[] = [], uv: number[] = [], nor: number[] = [], col: number[] = [], tint: number[] = [], idx: number[] = [];
  const base = new Color(color);
  for (let j = 0; j <= NV; j++) {
    const v = j / NV;
    const edge = length * (1 - notch + notch * Math.abs(2 * v - 1));
    for (let i = 0; i <= NU; i++) {
      const u = i / NU;
      const x = u * edge, y = v * height;
      pos.push(x, y, 0);
      uv.push(x / length, v);
      nor.push(0, 0, 1);
      const k = 1 + (valueNoise3(x * 4, y * 4, 0, seed) - 0.5) * 0.12;
      col.push(base.r * k, base.g * k, base.b * k);
      tint.push(1);
    }
  }
  for (let j = 0; j < NV; j++) {
    for (let i = 0; i < NU; i++) {
      const a = j * (NU + 1) + i, b = a + 1, c = a + NU + 1, d = c + 1;
      idx.push(a, b, c, b, d, c);
    }
  }
  const g = new BufferGeometry();
  g.setAttribute('position', new BufferAttribute(new Float32Array(pos), 3));
  g.setAttribute('normal', new BufferAttribute(new Float32Array(nor), 3));
  g.setAttribute('uv', new BufferAttribute(new Float32Array(uv), 2));
  g.setAttribute('color', new BufferAttribute(new Float32Array(col), 3));
  g.setAttribute('aTint', new BufferAttribute(new Float32Array(tint), 1));
  g.setIndex(idx);
  g.computeBoundingSphere();
  g.computeBoundingBox();
  return g;
}

/** Fort merlon. `kangoore` = the rounded, slightly pointed bud silhouette of Maratha forts. */
export function merlonGeometry(style: 'kangoore' | 'square', w: number, h: number, d: number): BufferGeometry {
  if (style === 'square') {
    const g = new BoxGeometry(w, h, d);
    g.translate(0, h / 2, 0);
    return g;
  }
  const r = w / 2;
  const hb = h - r * 1.05;
  const s = new Shape();
  s.moveTo(-r, 0);
  s.lineTo(r, 0);
  s.lineTo(r, hb);
  s.quadraticCurveTo(r * 1.02, hb + r * 0.95, 0, h);
  s.quadraticCurveTo(-r * 1.02, hb + r * 0.95, -r, hb);
  s.lineTo(-r, 0);
  const g = new ExtrudeGeometry(s, { depth: d, bevelEnabled: true, bevelThickness: 0.04, bevelSize: 0.03, bevelSegments: 1, curveSegments: 7 });
  g.translate(0, 0, -d / 2);
  return g;
}

/** Star outline for the Diwali akash kandil. */
export function starShape(outer: number, inner: number, points: number): Shape {
  const s = new Shape();
  for (let i = 0; i <= points * 2; i++) {
    const a = (i / (points * 2)) * Math.PI * 2 + Math.PI / 2;
    const r = i % 2 === 0 ? outer : inner;
    const x = Math.cos(a) * r, y = Math.sin(a) * r;
    if (i === 0) s.moveTo(x, y); else s.lineTo(x, y);
  }
  return s;
}

/** Quaternion that rotates +Y onto `dir`. */
export function quatFromY(dir: Vector3): Quaternion {
  return new Quaternion().setFromUnitVectors(new Vector3(0, 1, 0), dir.clone().normalize());
}
